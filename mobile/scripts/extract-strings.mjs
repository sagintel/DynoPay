// Collects every UI string of the app (English source) into src/i18n/strings.gen.ts.
// Run: npm run i18n:extract. The list is what gets translated for languages not shipped with the app.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../src', import.meta.url));
const out = join(root, 'i18n', 'strings.gen.ts');

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return relative(root, p).startsWith('i18n') ? [] : files(p);
    return /\.(tsx?|jsx?)$/.test(name) ? [p] : [];
  });
}

const found = new Set();
// Things that look like code, not UI text.
const CODE = /\/\/|=>|[=<>;`[\]]|\$\{|\b(const|return|void|undefined)\b|['"]\s*[,:)}]|[?:]\s*['"]|_|^M\d|\d[a-z]\d|^[A-Z][a-z]+(-[A-Z][a-z]+)+$|^[A-Z]+$/;
const add = (raw) => {
  if (!raw) return;
  const s = raw.replace(/\\'/g, "'").replace(/\\"/g, '"');
  if (s.length < 2 || s.length > 240 || !/[A-Za-z]{2}/.test(s) || CODE.test(s)) return;
  if (/^\s+\w+\s*$/.test(s) || /^(X-|\$)/.test(s)) return;
  if (/^(@\/|\.\/|https?:|#|rgba?\(|[a-z]+:\/\/|\/)/.test(s) || /\.(tsx?|png|svg)$/.test(s) || /^[a-z]+([:_-][a-z]+)*$/.test(s)) return;
  found.add(s);
};

const PROPS = /\b(?:label|title|subtitle|placeholder|footer|accessibilityLabel|accessibilityHint|text|message|caption|emptyText|confirmLabel|doneLabel|hint|reason)\s*[:=]\s*\{?\s*(?:'([^'\n]+)'|"([^"\n]+)")/g;
const CALLS = /\b(?:t|tr|toast|setError|setStatus|lookup)\(\s*(?:'([^'\n]+)'|"([^"\n]+)")/g;
// Capitalised sentences/words in quotes (labels kept in objects, ternaries…). Lower-case ones come from t()/tr().
const LITERAL = /'([A-Z“][^'\n]*[a-z][^'\n]*)'|"([A-Z“][^"\n]*[a-z][^"\n]*)"/g;
const JSX_TEXT = />([^<>{}=;'"?]*[A-Za-z]{2}[^<>{}=;'"?]*)</g;

for (const file of files(root)) {
  const src = readFileSync(file, 'utf8').replace(/^import .*$/gm, '');
  for (const re of [PROPS, CALLS, LITERAL]) for (const m of src.matchAll(re)) add(m[1] ?? m[2]);
  // JSX trims each line of a text node and joins the lines with a space.
  for (const m of src.matchAll(JSX_TEXT)) {
    const text = m[1].includes('\n') ? m[1].split('\n').map((l) => l.trim()).filter(Boolean).join(' ') : m[1];
    if (text.trim() && !/&&|\|\|/.test(text)) add(text);
  }
}

// Texts the server sends while the assistant works (progress labels) and other non-literal sources.
for (const s of JSON.parse(readFileSync(join(root, 'i18n', 'extra.json'), 'utf8'))) found.add(s);

const list = [...found].sort((a, b) => a.localeCompare(b));
writeFileSync(
  out,
  `// Generated by scripts/extract-strings.mjs — do not edit by hand.\n/** Every UI string of the app, in English (the translation keys). */\nexport const UI_STRINGS: string[] = ${JSON.stringify(list, null, 2)};\n`,
);
console.log(`${list.length} strings → ${relative(process.cwd(), out)}`);
